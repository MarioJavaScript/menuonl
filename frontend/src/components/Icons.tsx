/**
 * Dietary tag badge rendering the proper badge icon and styling
 */
export function DietaryTagBadge({
  codigo,
  nombre,
  icono,
}: {
  codigo: string;
  nombre: string;
  icono?: string | null;
}) {
  const norm = codigo.toLowerCase().replace('-', '_');

  let badgeColor = 'bg-emerald-50 text-emerald-700 border-emerald-200 dark:bg-emerald-950/40 dark:text-emerald-300 dark:border-emerald-800/60';
  let IconComponent = IconLeaf;

  if (norm.includes('picante') || icono === 'flame') {
    badgeColor = 'bg-rose-50 text-rose-700 border-rose-200 dark:bg-rose-950/40 dark:text-rose-300 dark:border-rose-800/60';
    IconComponent = IconFlame;
  } else if (norm.includes('gluten') || icono === 'wheat-off') {
    badgeColor = 'bg-amber-50 text-amber-700 border-amber-200 dark:bg-amber-950/40 dark:text-amber-300 dark:border-amber-800/60';
    IconComponent = IconWheatOff;
  } else if (norm.includes('recomendado') || icono === 'star') {
    badgeColor = 'bg-indigo-50 text-indigo-700 border-indigo-200 dark:bg-indigo-950/40 dark:text-indigo-300 dark:border-indigo-800/60';
    IconComponent = IconStar;
  } else if (norm.includes('nuevo') || icono === 'sparkles') {
    badgeColor = 'bg-cyan-50 text-cyan-700 border-cyan-200 dark:bg-cyan-950/40 dark:text-cyan-300 dark:border-cyan-800/60';
    IconComponent = IconSparkles;
  }

  return (
    <span
      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-xs font-medium border ${badgeColor}`}
      title={nombre}
    >
      <IconComponent size={12} className="shrink-0" />
      <span>{nombre}</span>
    </span>
  );
}
